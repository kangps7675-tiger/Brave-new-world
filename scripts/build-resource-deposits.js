function hashNoise(seed, i) {
  const x = Math.sin(seed * 12.9898 + i * 78.233) * 43758.5453;
  return x - Math.floor(x);
}

function irregularRing(def) {
  const verts = def.verts ?? (IS_LITE ? 14 : 20);
  const rot = ((def.rot ?? 0) * Math.PI) / 180;
  const seed = def.seed ?? 1;
  const cosR = Math.cos(rot);
  const sinR = Math.sin(rot);
  const ring = [];

  for (let i = 0; i < verts; i += 1) {
    const t = (i / verts) * Math.PI * 2;
    const n1 = 0.62 + 0.38 * hashNoise(seed, i);
    const n2 = 1 + 0.22 * Math.sin(i * 2.15 + seed) + 0.12 * Math.cos(i * 3.7 + seed * 0.5);
    const rLat = def.ry * n1 * n2;
    const rLng = def.rx * n1 * n2 * (1 / Math.max(0.35, Math.cos((def.lat * Math.PI) / 180)));
    const dx = Math.cos(t) * rLng;
    const dy = Math.sin(t) * rLat;
    const lng = def.lng + dx * cosR - dy * sinR;
    const lat = def.lat + dx * sinR + dy * cosR;
    ring.push([roundCoord(lng, 3), roundCoord(lat, 3)]);
  }
  ring.push(ring[0]);
  return ring;
}

function toDeposit(def) {
  const ring = irregularRing(def);
  let minLat = Infinity;
  let maxLat = -Infinity;
  let minLng = Infinity;
  let maxLng = -Infinity;
  for (const [lng, lat] of ring) {
    minLat = Math.min(minLat, lat);
    maxLat = Math.max(maxLat, lat);
    minLng = Math.min(minLng, lng);
    maxLng = Math.max(maxLng, lng);
  }
  return {
    id: def.id,
    kind: "resource-deposit",
    name: def.name,
    mineral: def.mineral,
    country: def.country,
    center: { lat: roundCoord(def.lat, 3), lng: roundCoord(def.lng, 3) },
    geometry: { type: "Polygon", coordinates: [ring] },
    tier: def.tier ?? 1,
    linkedPointId: def.linkedPointId || null,
    bbox: {
      minLat: roundCoord(minLat, 3),
      minLng: roundCoord(minLng, 3),
      maxLat: roundCoord(maxLat, 3),
      maxLng: roundCoord(maxLng, 3),
    },
  };
}

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const list = IS_LITE ? DEPOSITS.filter((d) => (d.tier ?? 1) <= 2) : DEPOSITS;
  const deposits = list.map(toDeposit);
  writeJsonArrayFile(path.join(OUT_DIR, "resource-deposits.json"), deposits);
  console.log(`   resource-deposits: ${deposits.length}`);
}

