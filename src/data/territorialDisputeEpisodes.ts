export function territorialEpisodeById(
  id: string | null | undefined,
): TerritorialDisputeEpisode | null {
  if (!id) return null;
  return TERRITORIAL_DISPUTE_EPISODES.find((e) => e.id === id) ?? null;
}

export function episodesLinkedToHotspot(
  hotspotId: string,
): TerritorialDisputeEpisode[] {
  return TERRITORIAL_DISPUTE_EPISODES.filter((e) =>
    e.linkedHotspotIds.includes(hotspotId),
  );
}
